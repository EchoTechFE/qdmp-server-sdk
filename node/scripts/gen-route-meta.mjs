#!/usr/bin/env node
// Generates src/generated/route-meta.ts and src/generated/error-codes.ts from
// shared/generated/route-meta.json and shared/generated/error-codes.json
// (themselves produced by shared/scripts/gen-route-meta.mjs from the
// x-qdmp-auth-scheme / x-qdmp-token-required / x-error-codes extensions in
// shared/openapi.yaml).
//
// This is the Node-side half of a hand-written generator step: the three
// official codegen tools (openapi-typescript / oapi-codegen / openapi-generator)
// don't read those extension fields, so shared/scripts/gen-route-meta.mjs parses
// the spec into common JSON, and this script turns that JSON into the
// hand-consumable TypeScript modules the SDK actually imports — so
// src/generated/route-meta.ts and src/generated/error-codes.ts are real
// generated artifacts instead of hand-maintained mirrors. Run via
// `npm run codegen`.

import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const NODE_DIR = path.resolve(__dirname, '..');
const SHARED_ROUTE_META_PATH = path.resolve(
  NODE_DIR,
  '../shared/generated/route-meta.json',
);
const SHARED_ERROR_CODES_PATH = path.resolve(
  NODE_DIR,
  '../shared/generated/error-codes.json',
);
const ROUTE_META_OUT_PATH = path.join(NODE_DIR, 'src/generated/route-meta.ts');
const ERROR_CODES_OUT_PATH = path.join(
  NODE_DIR,
  'src/generated/error-codes.ts',
);

function generateRouteMeta() {
  const routeMeta = JSON.parse(readFileSync(SHARED_ROUTE_META_PATH, 'utf8'));

  const methods = [...new Set(routeMeta.map(r => r.method))].sort();
  const authSchemes = [...new Set(routeMeta.map(r => r.authScheme))].sort();

  const methodType = methods.map(m => `'${m}'`).join(' | ');
  const authSchemeType = authSchemes.map(s => `'${s}'`).join(' | ');

  const entries = routeMeta
    .map(
      r =>
        `  {\n` +
        `    operationId: '${r.operationId}',\n` +
        `    method: '${r.method}',\n` +
        `    path: '${r.path}',\n` +
        `    authScheme: '${r.authScheme}',\n` +
        `    tokenRequired: ${r.tokenRequired},\n` +
        `  },`,
    )
    .join('\n');

  const content = `/**
 * GENERATED FILE — DO NOT HAND-EDIT.
 *
 * Generated by scripts/gen-route-meta.mjs (\`npm run codegen\`) from
 * ../shared/generated/route-meta.json, which is itself generated by
 * shared/scripts/gen-route-meta.mjs from the x-qdmp-auth-scheme /
 * x-qdmp-token-required extensions in shared/openapi.yaml.
 *
 * To pick up a spec change: regenerate shared/generated/route-meta.json
 * first (see shared/scripts/gen-route-meta.mjs), then run \`npm run codegen\`
 * in node/ to regenerate this file, and diff it — do not edit it by hand.
 */

export type QdmpAuthScheme = ${authSchemeType};
export type QdmpHttpMethod = ${methodType};

export interface RouteMeta {
  operationId: string;
  method: QdmpHttpMethod;
  path: string;
  authScheme: QdmpAuthScheme;
  tokenRequired: boolean;
}

export const ROUTE_META: readonly RouteMeta[] = [
${entries}
];

const routeByOperationId = new Map<string, RouteMeta>(
  ROUTE_META.map(route => [route.operationId, route]),
);

/** Looks up a route's method/path/authScheme by operationId. Throws if the
 * operationId is unknown — this would indicate a drift between this
 * generated file and shared/openapi.yaml, which should never happen for
 * hand-authored callers using the operationIds defined above. */
export function getRouteMeta(operationId: string): RouteMeta {
  const route = routeByOperationId.get(operationId);
  if (!route) {
    throw new Error(\`qdmp-server-sdk: unknown operationId "\${operationId}"\`);
  }
  return route;
}
`;

  writeFileSync(ROUTE_META_OUT_PATH, content, 'utf8');
  console.log(`已生成 ${ROUTE_META_OUT_PATH}（${routeMeta.length} 条 route）`);
}

function generateErrorCodes() {
  const errorCodes = JSON.parse(readFileSync(SHARED_ERROR_CODES_PATH, 'utf8'));

  const entries = errorCodes
    .map(
      e =>
        `  {\n` +
        `    code: ${JSON.stringify(e.code)},\n` +
        `    name: '${e.name}',\n` +
        `    message: ${JSON.stringify(e.message)},\n` +
        `    source: ${JSON.stringify(e.source)},\n` +
        `  },`,
    )
    .join('\n');

  const constEntries = errorCodes
    .map(e => `  ${e.name}: ${JSON.stringify(e.code)},`)
    .join('\n');

  const content = `/**
 * GENERATED FILE — DO NOT HAND-EDIT.
 *
 * Generated by scripts/gen-route-meta.mjs (\`npm run codegen\`) from
 * ../shared/generated/error-codes.json, which is itself generated by
 * shared/scripts/gen-route-meta.mjs from the x-error-codes extension in
 * shared/openapi.yaml.
 *
 * These are the *known* qdmp error codes (documented ones plus ones
 * confirmed by real API traffic, e.g. 10005). This list is NOT a closed
 * enum — QdmpApiError.code stays typed as \`string | number\` (see
 * src/errors.ts) because undocumented codes are known to occur at runtime
 * (e.g. 20000, or small gateway-layer integers like 2 / 13). Use
 * QDMP_ERROR_CODE.REFRESH_TOKEN_EXPIRED etc. instead of hardcoding magic
 * numbers when checking against a *known* code; compare unknown codes via
 * QdmpApiError.code directly.
 *
 * To pick up a spec change: regenerate shared/generated/error-codes.json
 * first (see shared/scripts/gen-route-meta.mjs), then run \`npm run codegen\`
 * in node/ to regenerate this file, and diff it — do not edit it by hand.
 */

export interface KnownErrorCode {
  code: number;
  name: string;
  message: string;
  source: string;
}

export const KNOWN_ERROR_CODES: readonly KnownErrorCode[] = [
${entries}
];

/** Named constants for the known qdmp error codes, e.g.
 * \`err.code === QDMP_ERROR_CODE.REFRESH_TOKEN_EXPIRED\`. Not a closed enum —
 * see the module doc comment above. */
export const QDMP_ERROR_CODE = {
${constEntries}
} as const;
`;

  writeFileSync(ERROR_CODES_OUT_PATH, content, 'utf8');
  console.log(
    `已生成 ${ERROR_CODES_OUT_PATH}（${errorCodes.length} 条已知错误码）`,
  );
}

function main() {
  generateRouteMeta();
  generateErrorCodes();
}

main();
