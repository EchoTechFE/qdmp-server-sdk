package io.github.echotechfe.qdmp.generated;

import static org.assertj.core.api.Assertions.assertThat;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;
import org.junit.jupiter.api.Test;

/**
 * Cross-validates the checked-in generated {@link RouteMeta}/{@link KnownErrorCodes} against the
 * single source of truth they were generated from: {@code shared/generated/route-meta.json} and
 * {@code shared/generated/error-codes.json} (themselves generated by {@code
 * shared/scripts/gen-route-meta.mjs} from {@code shared/openapi.yaml}'s {@code
 * x-qdmp-auth-scheme}/{@code x-qdmp-token-required}/{@code x-error-codes} extensions).
 *
 * <p>Without this test, a spec change could silently drift from the checked-in generated Java files
 * -- e.g. someone edits {@code shared/openapi.yaml} and regenerates {@code
 * shared/generated/route-meta.json}, but forgets to also run {@code node
 * scripts/gen-route-meta.mjs} in {@code java/} -- and every business group would keep sending
 * requests built from stale route metadata with no test ever catching it.
 */
class RouteMetaCrossCheckTest {

  private static final ObjectMapper JSON = new ObjectMapper();

  @Test
  void routeMeta_matchesSharedGeneratedJson_operationByOperation() throws IOException {
    JsonNode sharedRouteMeta = readSharedGeneratedJson("route-meta.json");

    List<RouteMeta.Entry> javaEntries = RouteMeta.ALL;
    assertThat(javaEntries).hasSize(sharedRouteMeta.size());

    for (JsonNode expected : sharedRouteMeta) {
      String operationId = expected.get("operationId").asText();
      RouteMeta.Entry actual = RouteMeta.get(operationId);

      assertThat(actual.getMethod())
          .as("method for operationId=%s", operationId)
          .isEqualTo(expected.get("method").asText());
      assertThat(actual.getPath())
          .as("path for operationId=%s", operationId)
          .isEqualTo(expected.get("path").asText());
      assertThat(actual.getAuthScheme())
          .as("authScheme for operationId=%s", operationId)
          .isEqualTo(expected.get("authScheme").asText());
      assertThat(actual.isTokenRequired())
          .as("tokenRequired for operationId=%s", operationId)
          .isEqualTo(expected.get("tokenRequired").asBoolean());
    }
  }

  @Test
  void knownErrorCodes_matchesSharedGeneratedJson_codeByCode() throws IOException {
    JsonNode sharedErrorCodes = readSharedGeneratedJson("error-codes.json");

    List<Integer> expectedCodes = new ArrayList<>();
    for (JsonNode entry : sharedErrorCodes) {
      expectedCodes.add(entry.get("code").asInt());
    }

    // KnownErrorCodes exposes one `public static final int NAME = code;` constant per row of
    // shared/generated/error-codes.json; reflection lets this test verify that set without
    // hand-maintaining a duplicate list of names here (which would itself drift).
    List<Integer> actualCodes = new ArrayList<>();
    for (java.lang.reflect.Field field : KnownErrorCodes.class.getDeclaredFields()) {
      if (field.getType() == int.class) {
        try {
          actualCodes.add(field.getInt(null));
        } catch (IllegalAccessException e) {
          throw new AssertionError("failed to read KnownErrorCodes." + field.getName(), e);
        }
      }
    }

    assertThat(actualCodes)
        .as("KnownErrorCodes constants vs shared/generated/error-codes.json")
        .containsExactlyInAnyOrderElementsOf(expectedCodes);
  }

  private static JsonNode readSharedGeneratedJson(String fileName) throws IOException {
    Path path = findSharedGeneratedFile(fileName);
    try {
      return JSON.readTree(Files.readString(path));
    } catch (IOException e) {
      throw new UncheckedIOException("failed to read " + path, e);
    }
  }

  // Gradle normally runs tests with the java/ module directory as the working directory, so
  // "../shared/generated/<file>" resolves directly -- but this walks upward from the working
  // directory as a fallback in case a different runner sets a different cwd.
  private static Path findSharedGeneratedFile(String fileName) {
    Path direct = Paths.get("..", "shared", "generated", fileName);
    if (Files.exists(direct)) {
      return direct;
    }
    Path cursor = Paths.get("").toAbsolutePath();
    while (cursor != null) {
      Path candidate = cursor.resolve("shared/generated").resolve(fileName);
      if (Files.exists(candidate)) {
        return candidate;
      }
      cursor = cursor.getParent();
    }
    throw new IllegalStateException(
        "could not locate shared/generated/"
            + fileName
            + " from working directory "
            + Paths.get("").toAbsolutePath());
  }
}
