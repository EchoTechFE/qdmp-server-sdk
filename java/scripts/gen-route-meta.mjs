#!/usr/bin/env node
// Generates generated/src/main/java/io/github/echotechfe/qdmp/generated/{RouteMeta,KnownErrorCodes}.java
// from shared/generated/route-meta.json and shared/generated/error-codes.json (themselves
// produced by shared/scripts/gen-route-meta.mjs from the x-qdmp-auth-scheme /
// x-qdmp-token-required / x-error-codes extensions in shared/openapi.yaml).
//
// This is the Java-side half of a hand-written generator step (see node/scripts/gen-route-meta.mjs
// for the Node-side sibling): the three official codegen tools (openapi-typescript /
// oapi-codegen / openapi-generator) don't read those extension fields, so
// shared/scripts/gen-route-meta.mjs parses the spec into common JSON, and this script turns that
// JSON into hand-consumable Java classes that QdmpAuth and every business group actually import --
// so RouteMeta.java/KnownErrorCodes.java are real generated artifacts, not hand-maintained
// mirrors. Run via `node scripts/gen-route-meta.mjs` (or `./gradlew codegen`).

import {readFileSync, mkdirSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const JAVA_DIR = path.resolve(__dirname, '..');
const SHARED_ROUTE_META_PATH = path.resolve(
  JAVA_DIR,
  '../shared/generated/route-meta.json',
);
const SHARED_ERROR_CODES_PATH = path.resolve(
  JAVA_DIR,
  '../shared/generated/error-codes.json',
);
const GENERATED_PACKAGE_DIR = path.join(
  JAVA_DIR,
  'generated/src/main/java/io/github/echotechfe/qdmp/generated',
);
const ROUTE_META_OUT_PATH = path.join(GENERATED_PACKAGE_DIR, 'RouteMeta.java');
const KNOWN_ERROR_CODES_OUT_PATH = path.join(
  GENERATED_PACKAGE_DIR,
  'KnownErrorCodes.java',
);

function javaStringLiteral(value) {
  return JSON.stringify(String(value));
}

function generateRouteMeta() {
  const routeMeta = JSON.parse(readFileSync(SHARED_ROUTE_META_PATH, 'utf8'));

  const entries = routeMeta
    .map(
      r =>
        `      new Entry(\n` +
        `          ${javaStringLiteral(r.operationId)},\n` +
        `          ${javaStringLiteral(r.method)},\n` +
        `          ${javaStringLiteral(r.path)},\n` +
        `          ${javaStringLiteral(r.authScheme)},\n` +
        `          ${r.tokenRequired})`,
    )
    .join(',\n');

  const content = `package io.github.echotechfe.qdmp.generated;

import java.util.Arrays;
import java.util.Collections;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * GENERATED FILE -- DO NOT HAND-EDIT.
 *
 * <p>Generated by {@code scripts/gen-route-meta.mjs} ({@code node scripts/gen-route-meta.mjs},
 * or {@code ./gradlew codegen}) from {@code ../shared/generated/route-meta.json}, which is itself
 * generated by {@code shared/scripts/gen-route-meta.mjs} from the {@code x-qdmp-auth-scheme}/
 * {@code x-qdmp-token-required} extensions in {@code shared/openapi.yaml}.
 *
 * <p>To pick up a spec change: regenerate {@code shared/generated/route-meta.json} first (see
 * {@code shared/scripts/gen-route-meta.mjs}), then run {@code node scripts/gen-route-meta.mjs} in
 * {@code java/} to regenerate this file, and diff it -- do not edit it by hand.
 */
public final class RouteMeta {

  /** One row of the route metadata table: an operation's method/path/authScheme/tokenRequired. */
  public static final class Entry {
    private final String operationId;
    private final String method;
    private final String path;
    private final String authScheme;
    private final boolean tokenRequired;

    Entry(String operationId, String method, String path, String authScheme, boolean tokenRequired) {
      this.operationId = operationId;
      this.method = method;
      this.path = path;
      this.authScheme = authScheme;
      this.tokenRequired = tokenRequired;
    }

    public String getOperationId() {
      return operationId;
    }

    public String getMethod() {
      return method;
    }

    public String getPath() {
      return path;
    }

    public String getAuthScheme() {
      return authScheme;
    }

    public boolean isTokenRequired() {
      return tokenRequired;
    }
  }

  public static final List<Entry> ALL =
      Collections.unmodifiableList(
          Arrays.asList(
${entries}
          ));

  private static final Map<String, Entry> BY_OPERATION_ID = buildIndex();

  private static Map<String, Entry> buildIndex() {
    Map<String, Entry> map = new HashMap<>();
    for (Entry entry : ALL) {
      map.put(entry.getOperationId(), entry);
    }
    return Collections.unmodifiableMap(map);
  }

  /**
   * Looks up a route's method/path/authScheme/tokenRequired by operationId. Throws if the
   * operationId is unknown -- this would indicate a drift between this generated file and {@code
   * shared/openapi.yaml}, which should never happen for hand-authored callers using the
   * operationIds defined in {@code shared/generated/route-meta.json}.
   *
   * @param operationId the OpenAPI {@code operationId}, e.g. {@code "markAdd"}
   * @return the matching route metadata entry
   * @throws IllegalArgumentException if {@code operationId} is unknown
   */
  public static Entry get(String operationId) {
    Entry entry = BY_OPERATION_ID.get(operationId);
    if (entry == null) {
      throw new IllegalArgumentException("qdmp-server-sdk: unknown operationId \\"" + operationId + "\\"");
    }
    return entry;
  }

  private RouteMeta() {}
}
`;

  mkdirSync(GENERATED_PACKAGE_DIR, {recursive: true});
  writeFileSync(ROUTE_META_OUT_PATH, content, 'utf8');
  console.log(`已生成 ${ROUTE_META_OUT_PATH}（${routeMeta.length} 条 route）`);
}

function generateKnownErrorCodes() {
  const errorCodes = JSON.parse(readFileSync(SHARED_ERROR_CODES_PATH, 'utf8'));

  const constants = errorCodes
    .map(
      e =>
        `  /** {@code ${e.code}}: ${e.message}. Source: ${e.source} */\n` +
        `  public static final int ${e.name} = ${e.code};`,
    )
    .join('\n\n');

  const content = `package io.github.echotechfe.qdmp.generated;

/**
 * GENERATED FILE -- DO NOT HAND-EDIT.
 *
 * <p>Generated by {@code scripts/gen-route-meta.mjs} ({@code node scripts/gen-route-meta.mjs},
 * or {@code ./gradlew codegen}) from {@code ../shared/generated/error-codes.json}, which is itself
 * generated by {@code shared/scripts/gen-route-meta.mjs} from the {@code x-error-codes} extension
 * in {@code shared/openapi.yaml}.
 *
 * <p>These are the <em>known</em> qdmp error codes (documented ones plus ones confirmed by real
 * API traffic, e.g. {@code ACCESS_TOKEN_INVALID}). This list is NOT a closed enum -- {@link
 * io.github.echotechfe.qdmp.errors.QdmpApiError#getCode()} stays an open {@code String} because
 * undocumented codes are known to occur at runtime (e.g. {@code 20000}, or small gateway-layer
 * integers like {@code 2}/{@code 13}). Use e.g. {@code
 * String.valueOf(KnownErrorCodes.REFRESH_TOKEN_EXPIRED)} instead of hardcoding magic numbers when
 * checking against a <em>known</em> code; compare unknown codes via {@code QdmpApiError.getCode()}
 * directly.
 *
 * <p>To pick up a spec change: regenerate {@code shared/generated/error-codes.json} first (see
 * {@code shared/scripts/gen-route-meta.mjs}), then run {@code node scripts/gen-route-meta.mjs} in
 * {@code java/} to regenerate this file, and diff it -- do not edit it by hand.
 */
public final class KnownErrorCodes {

${constants}

  private KnownErrorCodes() {}
}
`;

  writeFileSync(KNOWN_ERROR_CODES_OUT_PATH, content, 'utf8');
  console.log(
    `已生成 ${KNOWN_ERROR_CODES_OUT_PATH}（${errorCodes.length} 条已知错误码）`,
  );
}

function main() {
  generateRouteMeta();
  generateKnownErrorCodes();
}

main();
